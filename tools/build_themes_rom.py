import os
import struct

def build_themes_nes_rom(out_path="TEMAS.NES"):
    # Read font from Bank 0 of EDFC/OS.BIN
    with open("EDFC/OS.BIN", "rb") as f:
        os_data = f.read()
    chr_rom = os_data[0x0000:0x2000] # 8KB CHR
    
    # 32KB PRG for Mapper 0
    prg = bytearray(0x8000)
    
    # Simple NROM 6502 code for TEMAS.NES
    # Reset Vector: $8000
    # NMI Vector: $8200
    
    # 6502 assembly for TEMAS.NES:
    # Boots, sets up PPU, displays title, instructions, and interactive theme selector
    listing = [
        # SEI, CLD, LDX #$FF, TXS
        0x78, 0xD8, 0xA2, 0xFF, 0x9A,
        # Disable rendering
        0xA9, 0x00, 0x8D, 0x00, 0x20, 0x8D, 0x01, 0x20,
        # Wait 2 VBlanks
        0x2C, 0x02, 0x20,
        # vblank 1
        0xAD, 0x02, 0x20, 0x10, 0xFB,
        # vblank 2
        0xAD, 0x02, 0x20, 0x10, 0xFB,
        
        # Load initial palette into PPU $3F00
        0xA9, 0x3F, 0x8D, 0x06, 0x20,
        0xA9, 0x00, 0x8D, 0x06, 0x20,
        0xA2, 0x00,
        # loop pal
        0xBD, 0x00, 0x84, # LDA $8400, X (first theme)
        0x8D, 0x07, 0x20,
        0xE8,
        0xE0, 0x20,
        0xD0, 0xF5,
        
        # Clear nametable $2000..$23BF with spaces (0x20)
        0xA9, 0x20, 0x8D, 0x06, 0x20,
        0xA9, 0x00, 0x8D, 0x06, 0x20,
        0xA9, 0x20, # space
        0xA2, 0x04,
        0xA0, 0x00,
        # clear loop
        0x8D, 0x07, 0x20,
        0x88,
        0xD0, 0xFA,
        0xCA,
        0xD0, 0xF7,
        
        # Write Title and Help Texts at $2082..
        # JSR print_screen_text
        0x20, 0x50, 0x81,
        
        # Reset scroll
        0xA9, 0x00,
        0x8D, 0x06, 0x20, 0x8D, 0x06, 0x20,
        0x8D, 0x05, 0x20, 0x8D, 0x05, 0x20,
        
        # Enable BG rendering & NMI
        0xA9, 0x80, 0x8D, 0x00, 0x20, # NMI on
        0xA9, 0x0A, 0x8D, 0x01, 0x20, # BG on
        
        # Main Loop: wait in infinite loop (NMI handles input & live palette)
        0x4C, 0x4B, 0x80, # JMP $804B
    ]
    
    prg[0x0000:len(listing)] = bytes(listing)
    
    # Subroutine print_screen_text at $8150 (offset 0x0150)
    # We can write directly to nametable strings
    STRINGS = [
        # (row, col, text)
        (2, 4, "SELETOR DE TEMAS EVERDRIVE"),
        (3, 4, "=========================="),
        (5, 2, "ATALHO NO SISTEMA EVERDRIVE:"),
        (6, 2, " SELECT + DIREITA  : PROXIMO"),
        (7, 2, " SELECT + ESQUERDA : ANTERIOR"),
        (9, 2, "TEMAS DISPONIVEIS:"),
        (11, 4, "1. CLASSICO EVERDRIVE"),
        (12, 4, "2. MATRIX HACKER (NEON)"),
        (13, 4, "3. CYBERPUNK 2077"),
        (14, 4, "4. GAME BOY RETRO (DMG)"),
        (15, 4, "5. AMBAR RETRO CRT"),
        (16, 4, "6. MIDNIGHT DARK OLED"),
        (17, 4, "7. CRIMSON FAMICOM"),
        (18, 4, "8. DEEP OCEAN (SAFIRA)"),
        (19, 4, "9. SYNTHWAVE SUNSET"),
        (22, 2, "USE DIRECIONAL ESQ/DIR P/ TESTAR"),
        (23, 2, "CORES MUDAM AO VIVO NA TV!"),
        (25, 4, "PRESSIONE START P/ INICIAR")
    ]
    
    # Encode strings into PRG starting at $8150
    p = 0x0150
    # Routine to write strings to nametable
    print_code = bytearray()
    for row, col, txt in STRINGS:
        vram_addr = 0x2000 + row * 32 + col
        # LDA #hi, STA $2006, LDA #lo, STA $2006
        print_code.extend([0xA9, vram_addr >> 8, 0x8D, 0x06, 0x20])
        print_code.extend([0xA9, vram_addr & 0xFF, 0x8D, 0x06, 0x20])
        for ch in txt:
            # LDA #ord, STA $2007
            print_code.extend([0xA9, ord(ch), 0x8D, 0x07, 0x20])
    print_code.append(0x60) # RTS
    prg[p:p+len(print_code)] = print_code
    
    # NMI Handler at $8200 (offset 0x0200)
    # Reads controller, switches palette on LEFT/RIGHT or SELECT+RIGHT/LEFT
    nmi_code = bytearray([
        0x48, 0x8A, 0x48, 0x98, 0x48, # PHA, TXA, PHA, TYA, PHA
        
        # Read controller
        0xA9, 0x01, 0x8D, 0x16, 0x40,
        0xA9, 0x00, 0x8D, 0x16, 0x40,
        0xA2, 0x08,
        0xA9, 0x00, 0x85, 0x00, # joy = 0
        # read bit loop ($8213)
        0xAD, 0x16, 0x40,
        0x4A,
        0x26, 0x00,
        0xCA,
        0xD0, 0xF8,
        
        # Edge detect with $01 (prev joy)
        0xA5, 0x00,
        0x45, 0x01,
        0x25, 0x00,
        0x85, 0x02, # new pressed buttons in $02
        
        # Check RIGHT (bit 0 = 0x01)
        0xA5, 0x02,
        0x29, 0x01,
        0xF0, 0x0E, # BEQ check_left
        
        # Next theme ($03 = theme index)
        0xE6, 0x03,
        0xA5, 0x03,
        0xC9, 0x09,
        0x90, 0x16, # BCC apply
        0xA9, 0x00,
        0x85, 0x03,
        0x4C, 0x41, 0x82, # JMP apply ($8241)
        
        # check_left ($8231)
        0xA5, 0x02,
        0x29, 0x02, # LEFT
        0xF0, 0x26, # BEQ exit
        
        # Prev theme
        0xA5, 0x03,
        0x38, 0xE9, 0x01,
        0x10, 0x02,
        0xA9, 0x08,
        0x85, 0x03,
        
        # apply ($8241)
        0xA5, 0x03,
        0x0A, 0x0A, 0x0A, 0x0A, # index * 16
        0xAA,
        
        # Stream palette to PPU $3F00
        0x2C, 0x02, 0x20,
        0xA9, 0x3F, 0x8D, 0x06, 0x20,
        0xA9, 0x00, 0x8D, 0x06, 0x20,
        0xA0, 0x00,
        # pal stream loop ($8253)
        0xBD, 0x00, 0x84, # LDA $8400, X
        0x8D, 0x07, 0x20,
        0xE8,
        0xC8,
        0xC0, 0x10,
        0xD0, 0xF5,
        
        # Reset scroll
        0xA9, 0x00,
        0x8D, 0x06, 0x20, 0x8D, 0x06, 0x20,
        0x8D, 0x05, 0x20, 0x8D, 0x05, 0x20,
        
        # exit ($826B)
        0xA5, 0x00,
        0x85, 0x01, # prev = current
        
        0x68, 0xA8, 0x68, 0xAA, 0x68,
        0x40 # RTI
    ])
    prg[0x0200:0x0200+len(nmi_code)] = nmi_code
    
    # Palette table at $8400 (offset 0x0400)
    THEME_PALETTES = [
        [0x0F, 0x10, 0x0F, 0x28, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x30, 0x00, 0x28], # Classico
        [0x0F, 0x2A, 0x0F, 0x39, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x30, 0x09, 0x39], # Matrix
        [0x02, 0x2C, 0x02, 0x24, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x30, 0x12, 0x24], # Cyberpunk
        [0x08, 0x19, 0x08, 0x38, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x30, 0x0A, 0x38], # Game Boy
        [0x0F, 0x17, 0x0F, 0x27, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x38, 0x07, 0x27], # Ambar
        [0x0F, 0x20, 0x0F, 0x21, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x31, 0x00, 0x21], # Dark OLED
        [0x0F, 0x16, 0x0F, 0x26, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x0F, 0x30, 0x06, 0x26], # Crimson
        [0x01, 0x21, 0x01, 0x3C, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x30, 0x11, 0x3C], # Ocean
        [0x04, 0x37, 0x04, 0x28, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x30, 0x14, 0x28], # Sunset
    ]
    p_pal = 0x0400
    for pal in THEME_PALETTES:
        prg[p_pal:p_pal+16] = bytes(pal)
        p_pal += 16
        
    # Vectors at $FFFA..$FFFF
    struct.pack_into("<H", prg, 0x7FFA, 0x8200) # NMI
    struct.pack_into("<H", prg, 0x7FFC, 0x8000) # RESET
    struct.pack_into("<H", prg, 0x7FFE, 0x8000) # IRQ
    
    # iNES Header: 32KB PRG, 8KB CHR, Mapper 0, vertical mirroring
    ines_hdr = b"NES\x1a\x02\x01\x01\x00" + b"\x00" * 8
    with open(out_path, "wb") as f:
        f.write(ines_hdr + prg + chr_rom)
    print(f"Generated {out_path} ({len(ines_hdr) + len(prg) + len(chr_rom)} bytes)!")

if __name__ == "__main__":
    build_themes_nes_rom("TEMAS.NES")
    build_themes_nes_rom("EDFC/THEMES.NES")
